-- ===================================================================
-- CampusPulse PostgreSQL Production Schema Definition (DDL)
-- Target: PostgreSQL 12+
-- Idempotent script supporting both fresh deployments and incremental migrations.
-- ===================================================================

-- 1. Accounts Table (Admins, Coordinators, Users)
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- Idempotent column additions for existing installations
ALTER TABLE admins ADD COLUMN IF NOT EXISTS name VARCHAR(100);
ALTER TABLE admins ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE INDEX IF NOT EXISTS idx_admins_email ON admins(email);
CREATE INDEX IF NOT EXISTS idx_admins_role ON admins(role);

-- 2. Campus Events Table
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    location VARCHAR(255) NOT NULL,
    start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    registration_deadline TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    max_capacity INTEGER,
    organizer_name VARCHAR(100) NOT NULL,
    contact_email VARCHAR(150) NOT NULL,
    whatsapp_number VARCHAR(20),
    banner_url VARCHAR(500),
    banner_public_id VARCHAR(255),
    qr_code_url VARCHAR(500),
    qr_code_public_id VARCHAR(255),
    registration_url VARCHAR(500),
    created_by_id BIGINT REFERENCES admins(id),
    reviewed_by_id BIGINT REFERENCES admins(id),
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    review_note VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- Idempotent column additions for existing installations
ALTER TABLE events ADD COLUMN IF NOT EXISTS banner_public_id VARCHAR(255);
ALTER TABLE events ADD COLUMN IF NOT EXISTS qr_code_url VARCHAR(500);
ALTER TABLE events ADD COLUMN IF NOT EXISTS qr_code_public_id VARCHAR(255);
ALTER TABLE events ADD COLUMN IF NOT EXISTS registration_url VARCHAR(500);
ALTER TABLE events ADD COLUMN IF NOT EXISTS created_by_id BIGINT REFERENCES admins(id);
ALTER TABLE events ADD COLUMN IF NOT EXISTS reviewed_by_id BIGINT REFERENCES admins(id);
ALTER TABLE events ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE events ADD COLUMN IF NOT EXISTS review_note VARCHAR(1000);

-- Performance & Discovery Query Indexes
CREATE INDEX IF NOT EXISTS idx_events_start_date ON events(start_date_time);
CREATE INDEX IF NOT EXISTS idx_events_status ON events(status);
CREATE INDEX IF NOT EXISTS idx_events_event_type ON events(event_type);
CREATE INDEX IF NOT EXISTS idx_events_status_start_date ON events(status, start_date_time);
CREATE INDEX IF NOT EXISTS idx_events_created_by ON events(created_by_id);

-- 3. Coordinator Requests Table
CREATE TABLE IF NOT EXISTS coordinator_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
    organization_or_club VARCHAR(150) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    contact_details VARCHAR(150),
    status VARCHAR(30) NOT NULL,
    requested_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    reviewed_by_id BIGINT REFERENCES admins(id),
    review_note VARCHAR(1000),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_coord_req_user ON coordinator_requests(user_id);
CREATE INDEX IF NOT EXISTS idx_coord_req_status ON coordinator_requests(status);
CREATE INDEX IF NOT EXISTS idx_coord_req_user_status ON coordinator_requests(user_id, status);

-- 4. Lightweight Audit Logs Table
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email VARCHAR(150) NOT NULL,
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(50) NOT NULL,
    target_id BIGINT,
    details TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON audit_logs(actor_email);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs(action);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(created_at);
