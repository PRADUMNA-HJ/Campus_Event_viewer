-- ===================================================================
-- CampusPulse PostgreSQL Production Schema Definition (DDL)
-- Target: PostgreSQL 12+
-- ===================================================================

-- 1. Administrators Table
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- 2. Campus Events Table
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    location VARCHAR(255) NOT NULL,
    start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    registration_deadline TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    max_capacity INTEGER,
    organizer_name VARCHAR(100) NOT NULL,
    contact_email VARCHAR(150) NOT NULL,
    whatsapp_number VARCHAR(20),
    banner_url VARCHAR(500),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- Performance & Discovery Query Indexes
CREATE INDEX IF NOT EXISTS idx_events_start_date ON events(start_date_time);
CREATE INDEX IF NOT EXISTS idx_events_status ON events(status);
CREATE INDEX IF NOT EXISTS idx_events_event_type ON events(event_type);
CREATE INDEX IF NOT EXISTS idx_events_status_start_date ON events(status, start_date_time);
CREATE INDEX IF NOT EXISTS idx_admins_email ON admins(email);
